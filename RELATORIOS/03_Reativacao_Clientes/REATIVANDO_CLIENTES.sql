-- View: REATIVANDO_CLIENTES
-- Banco: D:\Administracao\DB\ZEGRANDE\MIAUTOMEC.FDB
-- Objetivo: Identificar toda a base de clientes (50.457), categorizando entre:
--   1. Reativação de Compradores (33.621 clientes com histórico de compras em SAIDAESTOQUE)
--   2. Primeira Compra / Leads (16.836 clientes que nunca compraram)
-- Regra de Pedidos: Vendas finalizadas com STATUS IN (1, 3).

CREATE OR ALTER VIEW REATIVANDO_CLIENTES (
    CDCLIENTE,
    CLIENTE,
    RAZAO,
    CPFCNPJ,
    TELEFONE,
    CELULAR,
    TELEFONE2,
    EMAIL,
    ENDERECO,
    NUMERO,
    BAIRRO,
    SUBBAIRRO,
    CIDADE,
    UF,
    CEP,
    DTCADASTRO,
    DT_PRIMEIRA_COMPRA,
    DT_ULTIMA_COMPRA,
    DIAS_SEM_COMPRAR,
    FAIXA_INATIVIDADE,
    STATUS_REATIVACAO,
    TOTAL_PEDIDOS,
    VALOR_TOTAL_HISTORICO,
    TICKET_MEDIO,
    NRPEDIDO_ULTIMA_COMPRA,
    VALOR_ULTIMA_COMPRA,
    IDEMPRESA_ULTIMA_COMPRA,
    NOME_EMPRESA_ULTIMA_COMPRA,
    CDVENDEDOR_ULTIMA_COMPRA,
    VENDEDOR_ULTIMA_COMPRA,
    CDVENDEDOR_RESPONSAVEL,
    VENDEDOR_RESPONSAVEL,
    STATUS_CADASTRO
) AS
WITH RESUMO_COMPRAS AS (
    SELECT 
        SE.CDCLIENTE,
        COUNT(DISTINCT SE.NRPEDIDO) AS TOTAL_PEDIDOS,
        SUM(SE.VLTOTAL) AS VALOR_TOTAL_HISTORICO,
        MIN(SE.DTSAIDA) AS DT_PRIMEIRA_COMPRA,
        MAX(SE.DTSAIDA) AS DT_ULTIMA_COMPRA
    FROM SAIDAESTOQUE SE
    WHERE SE.STATUS IN (1, 3) 
      AND SE.CDCLIENTE IS NOT NULL 
    GROUP BY SE.CDCLIENTE
),
ULTIMO_PEDIDO AS (
    SELECT 
        SE.CDCLIENTE,
        SE.NRPEDIDO,
        SE.IDEMPRESA,
        SE.CDVENDEDOR,
        SE.VLTOTAL,
        ROW_NUMBER() OVER (PARTITION BY SE.CDCLIENTE ORDER BY SE.DTSAIDA DESC, SE.NRPEDIDO DESC) AS RN
    FROM SAIDAESTOQUE SE
    WHERE SE.STATUS IN (1, 3) 
      AND SE.CDCLIENTE IS NOT NULL 
)
/* PARTE 1: CLIENTES QUE JÁ COMPRARAM */
SELECT 
    C.CDCLIENTE,
    C.CLIENTE,
    C.RAZAO,
    CAST(COALESCE(C.CGC, '') AS VARCHAR(20)),
    C.TELEFONE,
    C.CELULAR,
    C.TELEFONE2,
    C.EMAIL,
    C.ENDERECO,
    C.NUMERO,
    C.BAIRRO,
    C.SUBBAIRRO,
    CAST(COALESCE(M.MUNICIPIO, '') AS VARCHAR(50)),
    CAST(COALESCE(C.UF, M.UF) AS VARCHAR(2)),
    C.CEP,
    C.CADASTRO,
    RC.DT_PRIMEIRA_COMPRA,
    RC.DT_ULTIMA_COMPRA,
    DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE),
    CAST(CASE 
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 30 THEN '01. ATE 30 DIAS (ATIVO)'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 60 THEN '02. 31 A 60 DIAS (RECENTE)'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 90 THEN '03. 61 A 90 DIAS (ALERTA)'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 180 THEN '04. 91 A 180 DIAS (OURO)'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 365 THEN '05. 181 A 365 DIAS (FRIO)'
        ELSE '06. MAIS DE 1 ANO (CRITICO)'
    END AS VARCHAR(35)),
    CAST(CASE 
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 30 THEN 'ATIVO'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 60 THEN 'RECENTE'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 90 THEN 'ALERTA'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 180 THEN 'OURO'
        WHEN DATEDIFF(DAY FROM CAST(RC.DT_ULTIMA_COMPRA AS DATE) TO CURRENT_DATE) <= 365 THEN 'FRIO'
        ELSE 'CRITICO'
    END AS VARCHAR(20)),
    RC.TOTAL_PEDIDOS,
    RC.VALOR_TOTAL_HISTORICO,
    CAST(RC.VALOR_TOTAL_HISTORICO / NULLIF(RC.TOTAL_PEDIDOS, 0) AS NUMERIC(15,2)),
    UP.NRPEDIDO,
    UP.VLTOTAL,
    UP.IDEMPRESA,
    CF.NOMEEMPRESA,
    UP.CDVENDEDOR,
    V.VENDEDOR,
    C.CDVENDEDOR,
    VR.VENDEDOR,
    CAST(CASE WHEN COALESCE(C.INATIVO, 0) = -1 THEN 'INATIVO' ELSE 'ATIVO' END AS VARCHAR(10))
FROM RESUMO_COMPRAS RC
JOIN ULTIMO_PEDIDO UP ON UP.CDCLIENTE = RC.CDCLIENTE AND UP.RN = 1
JOIN CLIENTE C ON C.CDCLIENTE = RC.CDCLIENTE
LEFT JOIN MUNICIPIO M ON M.CDMUNICIPIO = C.CDMUNICIPIO
LEFT JOIN CONFIGURACAO CF ON CF.IDEMPRESA = UP.IDEMPRESA
LEFT JOIN VENDEDOR V ON V.CDVENDEDOR = UP.CDVENDEDOR
LEFT JOIN VENDEDOR VR ON VR.CDVENDEDOR = C.CDVENDEDOR

UNION ALL

/* PARTE 2: CLIENTES QUE NUNCA COMPRARAM */
SELECT 
    C.CDCLIENTE,
    C.CLIENTE,
    C.RAZAO,
    CAST(COALESCE(C.CGC, '') AS VARCHAR(20)),
    C.TELEFONE,
    C.CELULAR,
    C.TELEFONE2,
    C.EMAIL,
    C.ENDERECO,
    C.NUMERO,
    C.BAIRRO,
    C.SUBBAIRRO,
    CAST(COALESCE(M.MUNICIPIO, '') AS VARCHAR(50)),
    CAST(COALESCE(C.UF, M.UF) AS VARCHAR(2)),
    C.CEP,
    C.CADASTRO,
    CAST(NULL AS TIMESTAMP),
    CAST(NULL AS TIMESTAMP),
    CAST(NULL AS INTEGER),
    CAST('00. NUNCA COMPROU' AS VARCHAR(35)),
    CAST('NUNCA COMPROU' AS VARCHAR(20)),
    0,
    0.00,
    0.00,
    CAST(NULL AS INTEGER),
    0.00,
    C.IDEMPRESA,
    CF.NOMEEMPRESA,
    CAST(NULL AS INTEGER),
    CAST(NULL AS VARCHAR(50)),
    C.CDVENDEDOR,
    VR.VENDEDOR,
    CAST(CASE WHEN COALESCE(C.INATIVO, 0) = -1 THEN 'INATIVO' ELSE 'ATIVO' END AS VARCHAR(10))
FROM CLIENTE C
LEFT JOIN MUNICIPIO M ON M.CDMUNICIPIO = C.CDMUNICIPIO
LEFT JOIN CONFIGURACAO CF ON CF.IDEMPRESA = C.IDEMPRESA
LEFT JOIN VENDEDOR VR ON VR.CDVENDEDOR = C.CDVENDEDOR
WHERE NOT EXISTS (
    SELECT 1 FROM SAIDAESTOQUE SE 
    WHERE SE.CDCLIENTE = C.CDCLIENTE 
      AND SE.STATUS IN (1, 3)
);

COMMIT WORK;
