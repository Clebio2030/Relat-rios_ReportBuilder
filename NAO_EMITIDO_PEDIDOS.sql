-- Regra: Traz pedidos/trocas NÃO EMITIDOS fiscais que NÃO SEJAM DINHEIRO
-- Agrupamento: 1 LINHA POR PEDIDO (agrupa parcelas do cartão/receber, eliminando duplicações)
-- Validação de não emitido: NF.NRDOC IS NULL (join com notas ativas)

CREATE OR ALTER VIEW NAO_EMITIDO_PEDIDOS (
    IDEMPRESA,
    NOMEEMPRESA,
    NRPEDIDO,
    DTSAIDA,
    HORAPED,
    CDCLIENTE,
    CLIENTE,
    CPFCNPJ,
    VLTOTAL_PEDIDO,
    SUBTOTAL_PEDIDO,
    DESCONTO_PEDIDO,
    STATUS_PEDIDO,
    TIPO_OPERACAO,
    CDVENDEDOR,
    NUMCUPOM,
    CHAVE_NFCE,
    OBS_PEDIDO,
    CONTROLE_CP,
    NRDOC_CP,
    PARCELA,
    VALOR_PARCELA,
    DTVENC,
    DTMOV,
    CODPAGTO,
    TPPAGTO,
    CAIXA,
    ORIGEM,
    FORMA_PAGTO,
    MEIO_PAGTO
) AS
SELECT 
    SE.IDEMPRESA,
    CF.NOMEEMPRESA,
    SE.NRPEDIDO,
    SE.DTSAIDA,
    SE.HORAPED,
    SE.CDCLIENTE,
    SE.CLIENTE,
    SE.CPFCNPJ,
    SE.VLTOTAL,
    SE.SUBTOTAL,
    SE.DESCONTO,
    SE.STATUS,
    CASE 
        WHEN SE.STATUS = 40 THEN 'TROCA'
        WHEN SE.STATUS = 0 THEN 'PEDIDO EM ABERTO'
        WHEN SE.STATUS IN (1, 3) THEN 'PEDIDO'
        ELSE 'OUTROS'
    END,
    SE.CDVENDEDOR,
    SE.NUMCUPOM,
    SE.CHAVE_NFCE,
    CAST(SE.OBS AS VARCHAR(255)),
    MAX(CP.CONTROLE),
    MAX(CP.NRDOC),
    COUNT(CP.CONTROLE),
    SUM(CP.VALOR),
    MAX(CP.DTVENC),
    MAX(CP.DTMOV),
    MIN(CP.CODPAGTO),
    MAX(CP.TPPAGTO),
    MAX(CP.CAIXA),
    MAX(CP.ORIGEM),
    CAST(LIST(DISTINCT TRIM(COALESCE(R.RECEBTO, '')), ', ') AS VARCHAR(255)),
    CAST(LIST(DISTINCT TRIM(COALESCE(R.MEIO_PAGTO, '')), ', ') AS VARCHAR(100))
FROM SAIDAESTOQUE SE
JOIN CONFIGURACAO CF 
    ON (CF.IDEMPRESA = SE.IDEMPRESA)
JOIN CTARECEBER_PROV CP 
    ON (CP.NRPEDIDO = SE.NRPEDIDO) 
   AND (CP.IDEMPRESA = SE.IDEMPRESA)
LEFT JOIN RECEBTO R 
    ON (R.CDRECEBTO = CP.CODPAGTO)
LEFT JOIN NOTAFISCAL NF 
    ON (NF.NRPEDIDO = SE.NRPEDIDO) 
   AND (NF.IDEMPRESA = SE.IDEMPRESA)
   AND (COALESCE(NF.NFE_CANCELADA, 0) = 0)
   AND (COALESCE(NF.STATUS, 0) <> 9)
WHERE SE.STATUS NOT IN (2, 42)
  AND (NF.NRDOC IS NULL)
  AND (UPPER(COALESCE(R.RECEBTO, '')) NOT LIKE '%DINHEIRO%')
  AND (CP.CODPAGTO NOT IN (1, 10))
GROUP BY 
    SE.IDEMPRESA,
    CF.NOMEEMPRESA,
    SE.NRPEDIDO,
    SE.DTSAIDA,
    SE.HORAPED,
    SE.CDCLIENTE,
    SE.CLIENTE,
    SE.CPFCNPJ,
    SE.VLTOTAL,
    SE.SUBTOTAL,
    SE.DESCONTO,
    SE.STATUS,
    SE.CDVENDEDOR,
    SE.NUMCUPOM,
    SE.CHAVE_NFCE,
    CAST(SE.OBS AS VARCHAR(255));

COMMIT WORK;
